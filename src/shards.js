// Laboratory 6: application-level sharding over 16 PostgreSQL databases (vnodes).
// Shard key = last hex character of the travel plan UUID. Locations reuse the
// same last character, so a location id alone is enough to find its database.
const fs = require('node:fs');
const crypto = require('node:crypto');
const { Pool, types } = require('pg');

types.setTypeParser(1082, value => value); // DATE stays YYYY-MM-DD in JSON.
types.setTypeParser(1700, value => Number(value)); // NUMERIC values in the API.

const SHARDS = '0123456789abcdef'.split('');
const SOURCE = process.env.MAPPING_SOURCE || 'file';
const FILE = process.env.MAPPING_FILE || 'config/mapping.json';
const PER_SHARD = Number(process.env.PG_POOL_PER_SHARD || 5);
const USER = process.env.PG_USER || 'traveler';
const PASSWORD = process.env.PG_PASSWORD || 'traveler';
const REGISTRY_URLS = (process.env.REGISTRY_URLS || '').split(',').filter(Boolean);
// Errors that mean "this database is no longer the owner of the shard":
// 42501 insufficient_privilege (REVOKE after a move), 3D000 database removed.
// Both are raised before the statement changes anything, so one retry is safe.
const MOVED = new Set(['42501', '3D000']);

let mapping = null;      // { version, source, shards: { '0': {host, port, database} } }
let reloading = null;    // single-flight reload promise
const pools = new Map(); // "host:port/database" -> pg.Pool

const shardOf = id => String(id).slice(-1).toLowerCase();
// New ids are generated by the API before INSERT (the database default is not used).
function newId(shard) {
  const id = crypto.randomUUID();
  return shard ? id.slice(0, -1) + shard : id;
}

function validate(candidate, source) {
  if (!candidate || !Number.isSafeInteger(candidate.version) || !candidate.shards) throw new Error(`Invalid mapping from ${source}`);
  for (const s of SHARDS) {
    const t = candidate.shards[s];
    if (!t || !t.host || !t.database) throw new Error(`Mapping ${source} has no target for shard ${s}`);
  }
  return { ...candidate, source };
}

async function readRegistry() {
  // Every registry copy is asked; the highest version wins, so a lagging
  // subscriber cannot roll the application back to an older mapping.
  const answers = await Promise.allSettled(REGISTRY_URLS.map(async url => {
    const client = new Pool({ connectionString: url, max: 1, connectionTimeoutMillis: 2000 });
    try {
      const { rows: meta } = await client.query('SELECT version FROM registry_meta WHERE id = 1');
      const { rows } = await client.query('SELECT shard, host, port, database FROM shard_map ORDER BY shard');
      const shards = Object.fromEntries(rows.map(r => [r.shard, { host: r.host, port: r.port, database: r.database }]));
      return { version: Number(meta[0].version), shards, url: url.replace(/\/\/[^@]*@/, '//') };
    } finally { await client.end(); }
  }));
  const ok = answers.filter(a => a.status === 'fulfilled').map(a => a.value).sort((a, b) => b.version - a.version);
  if (!ok.length) throw new Error('No shard registry replica is reachable');
  return validate(ok[0], `registry ${ok[0].url}`);
}

async function load() {
  if (SOURCE === 'registry') return readRegistry();
  return validate(JSON.parse(fs.readFileSync(FILE, 'utf8')), `file ${FILE}`);
}

async function reload(reason) {
  if (!reloading) reloading = (async () => {
    const previous = mapping && mapping.version;
    mapping = await load();
    console.log(JSON.stringify({ event: 'mapping_loaded', version: mapping.version, previous, source: mapping.source, reason }));
    return mapping;
  })().finally(() => { reloading = null; });
  return reloading;
}

function poolFor(target) {
  const key = `${target.host}:${target.port || 5432}/${target.database}`;
  if (!pools.has(key)) {
    const pool = new Pool({ host: target.host, port: target.port || 5432, database: target.database, user: USER,
      password: PASSWORD, max: PER_SHARD, connectionTimeoutMillis: 5000, idleTimeoutMillis: 30000 });
    pool.on('error', error => console.error(JSON.stringify({ event: 'idle_client_error', key, code: error.code })));
    pools.set(key, pool);
  }
  return pools.get(key);
}

async function current() { return mapping || reload('startup'); }
async function target(shard) {
  if (!SHARDS.includes(shard)) throw Object.assign(new Error('Unknown shard'), { code: 'SHARD' });
  return (await current()).shards[shard];
}

// Run fn(pool) on the shard that owns id. If the old database signals that it
// no longer owns the shard (revoked privileges, dropped database), the mapping
// is re-read once and the call is repeated on the new owner.
async function withShard(shard, fn) {
  const before = await current();
  try {
    return await fn(poolFor(before.shards[shard]));
  } catch (error) {
    if (!MOVED.has(error.code)) throw error;
    const after = await reload(`shard ${shard}: ${error.code}`);
    if (after.version === before.version && JSON.stringify(after.shards[shard]) === JSON.stringify(before.shards[shard])) throw error;
    console.log(JSON.stringify({ event: 'shard_retry', shard, from: before.shards[shard], to: after.shards[shard], version: after.version }));
    return fn(poolFor(after.shards[shard]));
  }
}

const query = (shard, text, params) => withShard(shard, pool => pool.query(text, params));

async function transaction(shard, fn) {
  return withShard(shard, async pool => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await fn(client);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally {
      client.release();
    }
  });
}

// Scatter-gather: the same statement on all 16 shards in parallel.
const all = (text, params) => Promise.all(SHARDS.map(s => query(s, text, params).then(r => ({ shard: s, rows: r.rows }))));

async function end() { await Promise.all([...pools.values()].map(p => p.end())); }
const info = () => mapping && { version: mapping.version, source: mapping.source, pools: pools.size };

module.exports = { SHARDS, shardOf, newId, query, transaction, all, reload, current, end, info };
