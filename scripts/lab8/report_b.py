import re


def shard_exec_total(name):
    m = re.search(r'(COMMIT on all 16 shards|DRY RUN: everything rolled back|ROLLBACK on all 16[^;]*); total (\d+) ms', (E / name).read_text(encoding='utf-8'))
    return m.group(1), int(m.group(2))


