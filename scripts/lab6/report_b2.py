# Section 6 (continued): where the bottleneck is, single-shard control test, summary used in conclusions.
def cpu_row(k):
    c = cpu(f'{k}-load')
    api = sum(v for n, v in c.items() if n.startswith('web'))
    pg = [v for n, v in c.items() if n.startswith('postgres')]
    return [NAMES[k], num(api, 0) + ' %', num(sum(pg), 0) + ' %', ' / '.join(num(v, 0) for v in pg)]


